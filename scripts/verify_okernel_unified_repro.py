#!/usr/bin/env python3
"""Rebuild the unified native monitor twice from captured source and tools.

This verifies monitor/DTB reproduction with fixed foreign Linux payload bytes.
It does not rebuild Linux, bootstrap the foreign toolchain, or qualify hardware.
All generated files stay in a newly created output directory.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shlex
import shutil
import subprocess
import sys
import time


ROOT = Path(__file__).resolve().parents[1]
SOURCES = (
    "ocore/kernel/build-aarch64-kernel-world-linux.sh",
    "ocore/kernel/aarch64/kernel_world/guest.dts",
    "ocore/kernel/aarch64/kernel_world/linker.ld",
    "ocore/kernel/aarch64/kernel_world/monitor.S",
    "ocore/runtime/aarch64/kernel_world_monitor.oc",
    "ocore/runtime/aarch64/kernel_world_virtio.oc",
    "ocore/runtime/aarch64/kernel_world_virtio_selftest.oc",
    "ocore/runtime/aarch64/kernel_world_net_host.oc",
    "ocore/runtime/aarch64/kernel_world_net.oc",
    "ocore/runtime/aarch64/kernel_world_9p.oc",
    "ocore/runtime/common/namespace_store.oc",
    "ocore/runtime/common/namespace_peer.oc",
)
PAYLOAD = ("Image", "initramfs.cpio", "linux-payload.json")
COMPARE = ("monitor.elf", "guest.dtb", "profile.oc", "guest.dts")


def identity(path: Path) -> dict:
    with path.open("rb") as stream:
        digest = hashlib.file_digest(stream, "sha256").hexdigest()
    return {"path": str(path.resolve()), "bytes": path.stat().st_size, "sha256": digest}


def strict_json(path: Path) -> dict:
    def unique(pairs):
        result = {}
        for key, value in pairs:
            if key in result:
                raise ValueError(f"duplicate JSON key {key!r}: {path}")
            result[key] = value
        return result

    def constant(value):
        raise ValueError(f"non-finite JSON value {value}: {path}")

    value = json.loads(path.read_text(), object_pairs_hook=unique, parse_constant=constant)
    if not isinstance(value, dict):
        raise ValueError(f"JSON object required: {path}")
    return value


def executable(value: str) -> Path:
    selected = shutil.which(value)
    if selected is None:
        raise ValueError(f"required executable missing: {value}")
    path = Path(selected).resolve()
    if not path.is_file() or not os.access(path, os.X_OK):
        raise ValueError(f"not an executable file: {path}")
    return path


def capture_file(source: Path, destination: Path) -> dict:
    before = identity(source)
    destination.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(source, destination)
    destination.chmod(0o444)
    copied = identity(destination)
    after = identity(source)
    if (before["bytes"], before["sha256"]) != (copied["bytes"], copied["sha256"]) or before != after:
        raise ValueError(f"input changed while capturing: {source}")
    return {"original": before, "frozen": copied}


def original_elf(path: Path) -> tuple[Path, dict]:
    """Recognize this repo's private-dependency wrapper without evaluating it."""
    environment = os.environ.copy()
    if path.read_bytes()[:4] == b"\x7fELF":
        return path, environment
    text = path.read_text()
    if "# Generated by scripts/bm-dev-env.sh; child-only library search." not in text:
        raise ValueError(f"only native ELF or bm-dev-env tool wrappers are supported: {path}")
    programs = [shlex.split(line) for line in text.splitlines() if line.startswith("exec ")]
    if len(programs) != 1 or len(programs[0]) != 3 or programs[0][2] != "$@":
        raise ValueError(f"unexpected private tool wrapper: {path}")
    for line in text.splitlines():
        if line.startswith("export LD_LIBRARY_PATH="):
            value = shlex.split(line)[1].split("=", 1)[1].split("${", 1)[0]
            if "$" in value or "`" in value:
                raise ValueError(f"nonliteral wrapper library path: {path}")
            environment["LD_LIBRARY_PATH"] = value + (":" + environment["LD_LIBRARY_PATH"] if environment.get("LD_LIBRARY_PATH") else "")
    result = Path(programs[0][1]).resolve()
    if result.read_bytes()[:4] != b"\x7fELF":
        raise ValueError(f"wrapper does not select a native ELF: {result}")
    return result, environment


def freeze_tool(name: str, original: Path, output: Path) -> dict:
    binary, environment = original_elf(original)
    tool_directory = output / "tools"
    native = tool_directory / "native" / name
    record = {"selected": identity(original), "native": capture_file(binary, native)}
    native.chmod(0o555)
    dynamic = subprocess.run(["ldd", str(binary)], env=environment, capture_output=True, text=True, timeout=20)
    dependencies = []
    loader = None
    if dynamic.returncode != 0 and "not a dynamic executable" not in dynamic.stdout + dynamic.stderr and "statically linked" not in dynamic.stdout + dynamic.stderr:
        raise ValueError(f"cannot resolve native tool dependencies: {binary}: {dynamic.stdout}{dynamic.stderr}")
    if "not found" in dynamic.stdout:
        raise ValueError(f"unresolved native tool dependency: {binary}: {dynamic.stdout}")
    for line in dynamic.stdout.splitlines():
        match = re.search(r"(?:=>\s+)?(/\S+)\s+\(0x", line)
        if not match:
            continue
        dependency = Path(match.group(1)).resolve()
        # Preserve DT_NEEDED names, not just symlink targets (libstdc++.so.6
        # must remain discoverable even if its original ELF was ...so.6.0.33).
        needed = line.split("=>", 1)[0].strip() if "=>" in line else Path(match.group(1)).name
        if Path(needed).name != needed:
            raise ValueError(f"unexpected dynamic dependency name: {needed}")
        target = tool_directory / "lib" / needed
        if target.exists():
            if identity(target)["sha256"] != identity(dependency)["sha256"]:
                raise ValueError(f"incompatible dependency sonames: {target.name}")
            dependency_record = {"original": identity(dependency), "frozen": identity(target)}
        else:
            dependency_record = capture_file(dependency, target)
        dependencies.append(dependency_record)
        if "ld-linux" in dependency.name:
            target.chmod(0o555)
            loader = target
    if dependencies and loader is None:
        raise ValueError(f"ELF interpreter was not resolved: {binary}")
    wrapper = tool_directory / "bin" / name
    wrapper.parent.mkdir(parents=True, exist_ok=True)
    # Execute the ELF itself: invoking ld-linux as argv[0] makes Clang mistake
    # the loader for its own -cc1 subprocess. Its recorded PT_INTERP remains a
    # fixed host dependency; DSOs are taken from the captured private closure.
    prelude = "#!/bin/sh\n"
    if loader is not None:
        prelude += "export LD_LIBRARY_PATH=" + shlex.quote(str(tool_directory / "lib")) + "\n"
    wrapper.write_text(prelude + "exec " + shlex.quote(str(native)) + ' "$@"\n')
    wrapper.chmod(0o555)
    version_argv = [str(wrapper), "--version"]
    result = subprocess.run(version_argv, capture_output=True, text=True, timeout=20)
    if result.returncode != 0:
        raise ValueError(f"frozen tool cannot execute: {name}: {result.stdout}{result.stderr}")
    runtime_environment = dict(environment, LD_LIBRARY_PATH=str(tool_directory / "lib"))
    runtime = subprocess.run(["ldd", str(native)], env=runtime_environment, capture_output=True, text=True, timeout=20)
    for line in runtime.stdout.splitlines():
        match = re.search(r"=>\s+(/\S+)\s+\(0x", line)
        if match and Path(match.group(1)).resolve().parent != (tool_directory / "lib").resolve():
            raise ValueError(f"captured tool falls back to an uncaptured host DSO: {name}: {line}")
    if "not found" in runtime.stdout:
        raise ValueError(f"captured tool has an unresolved DSO: {name}: {runtime.stdout}")
    record.update({"dependencies": dependencies, "elf_interpreter": "recorded host PT_INTERP; copied interpreter is retained as evidence, not substituted into ELF",
                   "wrapper": identity(wrapper), "version_argv": version_argv,
                   "version_stdout": result.stdout, "version_stderr": result.stderr,
                   "runtime_dso_resolution": runtime.stdout})
    return record


def normalized_profile(path: Path) -> dict:
    value = strict_json(path)
    if value.get("schema") != "ostadix.kernel-world-linux-monitor/v1" or value.get("profile") != "package-domain":
        raise ValueError(f"unexpected monitor profile: {path}")
    if value.get("network_grant", {}).get("enabled") is not True or value.get("namespace_grant", {}).get("enabled") is not True:
        raise ValueError(f"unified network/namespace grants are missing: {path}")
    for artifact in value["artifacts"].values():
        original = Path(artifact["path"])
        actual = identity(original)
        if actual["sha256"] != artifact["sha256"] or actual["bytes"] != artifact["bytes"]:
            raise ValueError(f"monitor manifest does not bind its artifact: {original}")
        artifact["path"] = original.name
    return value


def run(args: argparse.Namespace, output: Path) -> dict:
    started = time.time()
    source = args.source.resolve()
    payload = args.payload.resolve()
    evidence = {"schema": "ostadix.okernel-unified-monitor-repro/v1", "passed": False,
                "scope": "byte-identical native O-core AArch64 monitor, generated profile and DTB from captured source and fixed Linux payload bytes; no foreign-toolchain bootstrap, Linux rebuild, full Plan 9 ABI, or physical-hardware qualification",
                "verifier": identity(Path(__file__)), "original_source": str(source), "original_payload": str(payload),
                "source_inputs": {}, "payload_inputs": {}, "tools": {}, "builds": []}
    for relative in SOURCES:
        evidence["source_inputs"][relative] = capture_file(source / relative, output / "frozen-source" / relative)
    for relative in PAYLOAD:
        evidence["payload_inputs"][relative] = capture_file(payload / relative, output / "frozen-payload" / relative)
    for name, selection in (("ocorec", args.ocorec or str(source / "target/debug/ocorec")),
                            ("clang", args.clang), ("ld.lld", args.lld), ("dtc", args.dtc)):
        evidence["tools"][name] = freeze_tool(name, executable(selection), output)
    # The builder's interpreters remain explicit host dependencies. Native
    # compiler/assembler/linker/dtc ELF binaries and their loader/lib closure are
    # frozen above; this does not claim a bootstrapped hermetic host toolchain.
    for name, selection in (("bash", "bash"), ("python3", sys.executable)):
        path = executable(selection)
        evidence["tools"][name] = {"selected": identity(path), "scope": "fixed host interpreter binary; standard library remains a host dependency"}
        wrapper = output / "tools" / "bin" / name
        wrapper.write_text("#!/bin/sh\nexec " + shlex.quote(str(path)) + ' "$@"\n')
        wrapper.chmod(0o555)
    environment = {key: value for key, value in os.environ.items() if key in ("HOME", "USER", "LOGNAME", "TMPDIR")}
    environment.update({"PATH": str(output / "tools/bin") + ":/usr/bin:/bin", "LC_ALL": "C", "LANG": "C", "TZ": "UTC",
                        "SOURCE_DATE_EPOCH": "0", "PYTHONHASHSEED": "0", "OCORE_LINUX_PROFILE": "package-domain",
                        "OCORE_LINUX_NETWORK": "1", "OCORE_LINUX_NAMESPACE": "1", "OCORE_LINUX_BACKING_BYTES": str(args.backing_bytes),
                        "OCORE_LINUX_OCOREC_BIN": str(output / "tools/bin/ocorec"), "OCORE_LINUX_LLD": str(output / "tools/bin/ld.lld")})
    environment.pop("LD_PRELOAD", None)
    environment.pop("LD_LIBRARY_PATH", None)
    evidence["build_environment"] = {key: environment[key] for key in ("PATH", "LC_ALL", "LANG", "TZ", "SOURCE_DATE_EPOCH", "PYTHONHASHSEED", "OCORE_LINUX_PROFILE", "OCORE_LINUX_NETWORK", "OCORE_LINUX_NAMESPACE", "OCORE_LINUX_BACKING_BYTES", "OCORE_LINUX_OCOREC_BIN", "OCORE_LINUX_LLD")}
    for index in (1, 2):
        root = output / f"source-{index}"
        payload_copy = output / f"payload-{index}"
        shutil.copytree(output / "frozen-source", root)
        shutil.copytree(output / "frozen-payload", payload_copy)
        build = output / f"build-{index}"
        build_environment = dict(environment, OCORE_LINUX_BUILD_DIR=str(build), OCORE_LINUX_PAYLOAD_DIR=str(payload_copy))
        command = [str(output / "tools/bin/bash"), str(root / SOURCES[0])]
        log = output / f"build-{index}.log"
        with log.open("wb") as stream:
            result = subprocess.run(command, cwd=root, env=build_environment, stdout=stream, stderr=subprocess.STDOUT, timeout=args.timeout)
        evidence["builds"].append({"argv": command, "source": str(root), "payload": str(payload_copy), "output": str(build), "log": str(log), "exit_status": result.returncode})
        if result.returncode:
            raise ValueError(f"monitor build {index} failed; see {log}")
    evidence["artifacts"] = {}
    for name in COMPARE:
        left, right = output / "build-1" / name, output / "build-2" / name
        identical = left.read_bytes() == right.read_bytes()
        evidence["artifacts"][name] = {"byte_identical": identical, "build_1": identity(left), "build_2": identity(right)}
        if not identical:
            raise ValueError(f"independent monitor outputs differ: {name}")
    profiles = [normalized_profile(output / f"build-{index}/monitor-profile.json") for index in (1, 2)]
    if profiles[0] != profiles[1]:
        raise ValueError("monitor manifests differ beyond their independent artifact paths")
    expected_sources = {relative: record["frozen"]["sha256"] for relative, record in evidence["source_inputs"].items()}
    if profiles[0].get("source_sha256") != expected_sources:
        raise ValueError("monitor manifest does not identify the complete captured source closure")
    evidence["monitor_profile"] = {"normalized_identical": True, "normalization": "replace only artifact path values with basenames; hashes, sizes, grants, source identity and all other fields must remain equal",
                                   "build_1": identity(output / "build-1/monitor-profile.json"), "build_2": identity(output / "build-2/monitor-profile.json")}
    (output / "monitor-profile.normalized.json").write_text(json.dumps(profiles[0], sort_keys=True, indent=2) + "\n")
    for relative, record in evidence["source_inputs"].items():
        if identity(source / relative) != record["original"]:
            raise ValueError(f"source changed during reproduction: {relative}")
    for relative, record in evidence["payload_inputs"].items():
        if identity(payload / relative) != record["original"]:
            raise ValueError(f"foreign payload changed during reproduction: {relative}")
    for record in evidence["tools"].values():
        selected = record["selected"]
        if identity(Path(selected["path"])) != selected:
            raise ValueError(f"host tool changed during reproduction: {selected['path']}")
        if "native" in record:
            frozen = record["native"]["frozen"]
            if identity(Path(frozen["path"])) != frozen:
                raise ValueError(f"captured native tool changed: {frozen['path']}")
        for dependency in record.get("dependencies", []):
            frozen = dependency["frozen"]
            if identity(Path(frozen["path"])) != frozen:
                raise ValueError(f"captured native dependency changed: {frozen['path']}")
            if "ld-linux" in Path(dependency["original"]["path"]).name:
                original = dependency["original"]
                if identity(Path(original["path"])) != original:
                    raise ValueError(f"host ELF interpreter changed during reproduction: {original['path']}")
    evidence["passed"] = True
    evidence["elapsed_seconds"] = round(time.time() - started, 3)
    return evidence


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=ROOT)
    parser.add_argument("--payload", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True, help="new evidence directory; existing paths are refused")
    parser.add_argument("--ocorec")
    parser.add_argument("--clang", default="clang")
    parser.add_argument("--lld", default="ld.lld")
    parser.add_argument("--dtc", default="dtc")
    parser.add_argument("--backing-bytes", type=int, default=536870912)
    parser.add_argument("--timeout", type=int, default=180)
    args = parser.parse_args()
    output = args.output.absolute()
    if output.exists() or output.is_symlink():
        parser.error(f"output must be a new directory: {output}")
    output.mkdir(parents=True)
    try:
        evidence = run(args, output)
    except (ValueError, OSError, subprocess.SubprocessError) as error:
        evidence = {"schema": "ostadix.okernel-unified-monitor-repro/v1", "passed": False, "error": str(error), "output": str(output)}
        (output / "result.json").write_text(json.dumps(evidence, indent=2) + "\n")
        print(f"Unified monitor reproduction: FAIL: {error}\nEvidence: {output / 'result.json'}", file=sys.stderr)
        return 1
    (output / "result.json").write_text(json.dumps(evidence, indent=2) + "\n")
    print(f"Unified monitor reproduction: PASS\nEvidence: {output / 'result.json'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
