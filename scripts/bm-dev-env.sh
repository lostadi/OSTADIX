#!/usr/bin/env bash
# Source for a checkout-local development shell, or run with a command:
#   source scripts/bm-dev-env.sh
#   scripts/bm-dev-env.sh python3 -m unittest tests.test_ocore_llvm_import
# This never edits shell startup files or changes the canonical ~/OSTADIX tree.

_ostadix_bm_dev_env() {
  local script_path=${BASH_SOURCE[0]} script_directory root
  script_directory=$(CDPATH= cd -- "$(dirname -- "$script_path")" && pwd -P) || return
  root=$(CDPATH= cd -- "$script_directory/.." && pwd -P) || return
  local host_root="${XDG_DATA_HOME:-$HOME/.local/share}/ostadix/bm-dev/host"
  local tools_directory="$root/target/bm-dev-env/bin"
  local sdk_bin="${XDG_CACHE_HOME:-$HOME/.cache}/ostadix-toolchains/llvm-22.1.6/sdk/LLVM-22.1.6-Linux-X64/bin"
  local library_search="" directory tool tool_name wrapper temporary
  local marker='# Generated by scripts/bm-dev-env.sh; child-only library search.'

  if [[ -L "$tools_directory" || ( -e "$tools_directory" && ! -d "$tools_directory" ) ]]; then
    printf 'bm-dev-env: tool directory must be a regular directory: %s\n' "$tools_directory" >&2
    return 1
  fi
  mkdir -p -- "$tools_directory" || return
  for directory in "$host_root/usr/lib/x86_64-linux-gnu" "$host_root/lib/x86_64-linux-gnu" \
      "$host_root/usr/lib" "$host_root/lib"; do
    if [[ -d "$directory" ]]; then
      library_search="${library_search:+$library_search:}$directory"
    fi
  done
  # A private Debian package sysroot supplies optional cross-ISA tools without
  # sudo. Give each executable its own library environment; unrelated commands
  # and the calling shell must retain their existing LD_LIBRARY_PATH.
  for tool in "$host_root/usr/bin/"* "$host_root/usr/sbin/"*; do
    [[ -f "$tool" && -x "$tool" ]] || continue
    tool_name=${tool##*/}
    case "$tool_name" in o|O|o-cli|ocorec|olangc) continue ;; esac
    wrapper="$tools_directory/$tool_name"
    if [[ -e "$wrapper" || -L "$wrapper" ]]; then
      if [[ -L "$wrapper" || ! -f "$wrapper" ]] || ! grep -qFx -- "$marker" "$wrapper"; then
        printf 'bm-dev-env: preserving unexpected tool wrapper: %s\n' "$wrapper" >&2
        return 1
      fi
    fi
    temporary=$(mktemp "$tools_directory/.wrapper.XXXXXXXX") || return
    if ! {
      printf '#!/bin/bash\n%s\n' "$marker"
      if [[ -n "$library_search" ]]; then
        printf 'export LD_LIBRARY_PATH=%q"${LD_LIBRARY_PATH:+:${LD_LIBRARY_PATH}}"\n' "$library_search"
      fi
      printf 'exec %q "$@"\n' "$tool"
    } > "$temporary"; then
      rm -f -- "$temporary"
      return 1
    fi
    if ! chmod 0755 "$temporary" || ! mv -f -- "$temporary" "$wrapper"; then
      rm -f -- "$temporary"
      return 1
    fi
  done

  local selected_evaluator="" selected_ocorec="" selected_olangc="" selected_front_door=""
  for directory in "$root/target/debug" "$root/target/release"; do
    if [[ -z "$selected_evaluator" && -x "$directory/O" ]]; then selected_evaluator="$directory/O"; fi
    if [[ -z "$selected_ocorec" && -x "$directory/ocorec" ]]; then selected_ocorec="$directory/ocorec"; fi
    if [[ -z "$selected_olangc" && -x "$directory/olangc" ]]; then selected_olangc="$directory/olangc"; fi
    if [[ -z "$selected_front_door" && -x "$directory/o-cli" ]]; then selected_front_door="$directory/o-cli"; fi
  done
  if [[ -n "$selected_front_door" ]]; then
    # This alias is the native executable itself, never an o() shell function.
    if [[ -e "$tools_directory/o" && ! -L "$tools_directory/o" ]]; then
      printf 'bm-dev-env: preserving unexpected native o entry: %s\n' "$tools_directory/o" >&2
      return 1
    fi
    ln -sfn -- "$selected_front_door" "$tools_directory/o" || return
    export O_LANG_OCLI_BIN="$selected_front_door"
  fi
  export O_LANG_ROOT="$root" O_BACKENDS_DIR="$root/backends"
  export RUSTUP_TOOLCHAIN=1.97.1
  if [[ -n "$selected_evaluator" ]]; then export O_LANG_EVALUATOR_BIN="$selected_evaluator"; fi
  if [[ -n "$selected_ocorec" ]]; then export OCOREC="$selected_ocorec" O_LANG_OCOREC_BIN="$selected_ocorec"; fi
  if [[ -n "$selected_olangc" ]]; then export OLANGC="$selected_olangc" O_LANG_OLANGC_BIN="$selected_olangc"; fi

  # Re-sourcing keeps the search path stable instead of accumulating copies.
  local retained_path="" part remaining_path="${PATH:-}" last_part=false
  while [[ "$last_part" == false ]]; do
    if [[ "$remaining_path" == *:* ]]; then
      part=${remaining_path%%:*}
      remaining_path=${remaining_path#*:}
    else
      part=$remaining_path
      last_part=true
    fi
    case "$part" in
      "$tools_directory"|"$root/target/debug"|"$root/target/release"|"$sdk_bin"|"$HOME/.cargo/bin"|"$HOME/.local/bin") ;;
      *) retained_path="${retained_path:+$retained_path:}$part" ;;
    esac
  done
  export PATH="$tools_directory:$root/target/debug:$root/target/release:$HOME/.cargo/bin:$HOME/.local/bin${retained_path:+:$retained_path}"

  # An absent or mismatched SDK remains absent: never relabel system Clang as
  # the exact original frontend required by native source-capture evidence.
  local sdk_ready=true version
  for tool_name in clang clang++ llvm-nm llvm-ar llvm-as llvm-dis llvm-readobj \
      llvm-objdump llvm-objcopy llvm-dwarfdump ld.lld; do
    if [[ ! -x "$sdk_bin/$tool_name" ]]; then sdk_ready=false; break; fi
    if ! version=$("$sdk_bin/$tool_name" --version 2>/dev/null) \
        || [[ ! "$version" =~ (clang\ version|LLVM\ version|LLD)[[:space:]]22\.1\.6([[:space:]]|$) ]]; then
      sdk_ready=false
      break
    fi
  done
  if [[ "$sdk_ready" == true ]]; then
    export OCORE_TEST_LLVM22_BIN="$sdk_bin" OCORE_LLVM22_BIN="$sdk_bin"
    export OCORE_TEST_CLANG22="$sdk_bin/clang" LD_LLD="$sdk_bin/ld.lld"
    export PATH="$tools_directory:$root/target/debug:$root/target/release:$sdk_bin:$HOME/.cargo/bin:$HOME/.local/bin${retained_path:+:$retained_path}"
  else
    # If a previously selected SDK disappears or changes, re-sourcing must not
    # leave this helper's earlier selection looking qualified. Explicit caller
    # selections at other paths remain the caller's responsibility.
    if [[ ${OCORE_TEST_LLVM22_BIN:-} == "$sdk_bin" ]]; then unset OCORE_TEST_LLVM22_BIN; fi
    if [[ ${OCORE_LLVM22_BIN:-} == "$sdk_bin" ]]; then unset OCORE_LLVM22_BIN; fi
    if [[ ${OCORE_TEST_CLANG22:-} == "$sdk_bin/clang" ]]; then unset OCORE_TEST_CLANG22; fi
    if [[ ${LD_LLD:-} == "$sdk_bin/ld.lld" ]]; then unset LD_LLD; fi
  fi

  local sysroot parser digest
  if command -v rustup >/dev/null 2>&1 \
      && sysroot=$(rustup run 1.97.1 rustc --print sysroot 2>/dev/null); then
    parser="$sysroot/lib/libLLVM.so.22.1-rust-1.97.1-stable"
    if [[ -f "$parser" ]] && command -v python3 >/dev/null 2>&1; then
      # Hash the ELF, not Rust's similarly named linker script. Check the
      # library version before publishing a machine-specific explicit pin.
      if digest=$(python3 - "$parser" <<'PY'
import ctypes
import hashlib
from pathlib import Path
import sys

path = Path(sys.argv[1])
with path.open("rb") as stream:
    if stream.read(4) != b"\x7fELF":
        raise SystemExit("bm-dev-env: Rust LLVM parser is not an ELF library")
    stream.seek(0)
    digest = hashlib.file_digest(stream, "sha256").hexdigest()
library = ctypes.CDLL(str(path))
library.LLVMGetVersion.argtypes = [ctypes.POINTER(ctypes.c_uint)] * 3
library.LLVMGetVersion.restype = None
version = [ctypes.c_uint() for _ in range(3)]
library.LLVMGetVersion(*(ctypes.byref(value) for value in version))
if tuple(value.value for value in version) != (22, 1, 6):
    raise SystemExit("bm-dev-env: Rust LLVM parser must report exactly 22.1.6")
print(digest)
PY
      ); then
        export OCORE_TEST_LLVM_LIBRARY="$parser" OCORE_TEST_LLVM_SHA256="$digest"
      else
        return 1
      fi
    fi
  fi
}

if [[ ${BASH_SOURCE[0]} != "$0" ]]; then
  _ostadix_bm_dev_env
else
  if [[ ${1:-} == --help || ${1:-} == -h || $# == 0 ]]; then
    printf 'Usage: source scripts/bm-dev-env.sh\n       scripts/bm-dev-env.sh COMMAND [ARGS...]\n'
    exit 0
  fi
  _ostadix_bm_dev_env || exit $?
  exec "$@"
fi
