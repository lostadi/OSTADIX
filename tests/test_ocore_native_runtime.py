import unittest

ROOT = Path(__file__).resolve().parents[1]
SDK_DEFAULT = (Path.home()/".cache/ostadix-toolchains/llvm-22.1.6/sdk/"
               "LLVM-22.1.6-Linux-X64/bin")
FLAGS = ["-O1","-ffreestanding","-fno-builtin","-fno-vectorize","-fno-slp-vectorize",
         "-fno-pic","-fno-pie","-fno-unwind-tables","-fno-asynchronous-unwind-tables",
         "-fno-stack-protector"]


def run(argv, **kwargs):
    result = subprocess.run([str(value) for value in argv],capture_output=True,text=True,timeout=120,**kwargs)
    if result.returncode:
        raise RuntimeError(f"command failed ({result.returncode}): {argv}\n{result.stdout}{result.stderr}")
    return result


class NativeRuntimeAdmissionTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.olangc = ROOT/"target/debug/olangc"
        cls.ocorec = ROOT/"target/debug/ocorec"
        cls.sdk = Path(os.environ.get("OCORE_TEST_LLVM22_BIN",str(SDK_DEFAULT)))
        for path in [cls.olangc,cls.ocorec,*[cls.sdk/name for name in ("clang","clang++","llvm-nm")]]:
            if not path.is_file() or not os.access(path,os.X_OK):
                raise unittest.SkipTest(f"actual olangc/ocorec and scoped LLVM22 SDK required: {path}")
        if shutil.which("git") is None:
            raise unittest.SkipTest("Git required for actual pinned source capture")
        for name in ("clang","clang++","llvm-nm"):
            version = run([cls.sdk/name,"--version"]).stdout
            if not re.search(r"\b(?:clang version|LLVM version) 22\.1\.6(?:\s|$)",version):
                raise RuntimeError(f"fixture requires exact LLVM22.1.6 {name}: {version}")
        native_arch = {"AMD64":"x86_64", "arm64":"aarch64"}.get(platform.machine(),platform.machine())
        if native_arch not in {"x86_64","aarch64","riscv64"}:
            raise unittest.SkipTest(f"this host CLI carrier fixture requires a supported native ISA: {native_arch}")
        if run([cls.sdk/"clang","-dumpmachine"]).stdout.strip().split("-")[0] != native_arch:
            raise unittest.SkipTest("the LLVM22 SDK must compile for this host's native ISA")
        cls.native_target = f"{native_arch}-unknown-none"
        cls.import_options = []
        library = os.environ.get("OCORE_TEST_LLVM_LIBRARY")
        expected_digest = os.environ.get("OCORE_TEST_LLVM_SHA256")
        if expected_digest and not library:
            raise RuntimeError("OCORE_TEST_LLVM_SHA256 requires OCORE_TEST_LLVM_LIBRARY")
        if library:
            library = Path(library).expanduser().resolve(strict=True)
            actual_digest = hashlib.sha256(library.read_bytes()).hexdigest()
            if expected_digest and actual_digest != expected_digest:
                raise RuntimeError("explicit LLVM22 parser digest differs from OCORE_TEST_LLVM_SHA256")
            cls.import_options = ["--llvm-library",str(library),"--llvm-sha256",actual_digest]
        if "--native-runtime" not in run([cls.olangc,"--help"]).stdout:
            raise RuntimeError("rebuild olangc with current --native-runtime implementation")
        retained = os.environ.get("OCORE_TEST_NATIVE_RUNTIME_OUTPUT_DIR")
        cls.retain_artifacts = bool(retained)
        if retained:
            evidence = Path(retained).expanduser().resolve()
            evidence.mkdir(parents=True,exist_ok=True)
            cls.directory = Path(tempfile.mkdtemp(prefix="run-",dir=evidence))
        else:
            cls.temporary = tempfile.TemporaryDirectory(prefix="ocore-native-runtime-test-")
            cls.addClassCleanup(cls.temporary.cleanup)
            cls.directory = Path(cls.temporary.name)
        cls.source,cls.build,cls.capture = [cls.directory/name for name in ("source","build","capture")]
        cls.source.mkdir()
        (cls.source/"runtime.c").write_text('''__attribute__((noinline))
unsigned long long engine_add(unsigned long long a, unsigned long long b) { return a + b; }
__attribute__((noinline)) int cold_path(int value) { return value - 7; }
int main(void) { return engine_add(5, 3) != 8; }
''')
        # The complete build inventory is generated by this pinned upstream
        # fixture build, not invented afterward by the lowering test.
        (cls.source/"build.py").write_text('''import hashlib,json,os,pathlib,subprocess,sys
source=pathlib.Path(sys.argv[1]); stage=sys.argv[2]; flags=json.loads(sys.argv[3])
cc=os.environ["CC"]
if stage == "configure":
    pathlib.Path("conftest.c").write_text("int configure_probe(void) { return 0; }\\n")
    subprocess.run([cc,*flags,"-c","conftest.c","-o","conftest.o"],check=True)
else:
    subprocess.run([cc,*flags,"-c",str(source/"runtime.c"),"-o","runtime.o"],check=True)
    subprocess.run([cc,"runtime.o","-no-pie","-o","app"],check=True)
    subprocess.run(["./app"],check=True)
    app=pathlib.Path("app").resolve()
    inventory={"schema":"ocore-runtime-unit-inventory-v1","complete":True,
      "units":[{"id":"full-runtime-source","kind":"clang","source":"runtime.c","build_step":"runtime-build","role":"runtime"}],
      "non_lowering_units":[{"id":"actual-configure-probe","kind":"clang",
         "source":str(pathlib.Path("conftest.c").resolve()),"build_step":"configure","role":"configure_probe",
         "evidence":{"reason":"Separate configure unit is absent from the captured final app link graph.",
           "artifacts":[{"path":str(app),"sha256":hashlib.sha256(app.read_bytes()).hexdigest(),"bytes":app.stat().st_size}]}}]}
    pathlib.Path("inventory.json").write_text(json.dumps(inventory))
''')
        for argv in [["git","init","-q"],["git","add","."],
                     ["git","-c","user.name=Native Runtime Test","-c","user.email=test@example.invalid",
                      "commit","-qm","complete source fixture"]]:
            run(argv,cwd=cls.source)
        revision = run(["git","rev-parse","HEAD"],cwd=cls.source).stdout.strip()
        recipe = {"schema":"ocore-runtime-recipe-v1","name":"actual-native-runtime-admission-fixture",
                  "source":{"url":"local-pinned-test-fixture","revision":revision},
                  "toolchain":{"llvm_version":"22.1.6"},
                  "commands":[{"name":stage,"argv":[sys.executable,"{source}/build.py","{source}",mode,json.dumps(FLAGS)]}
                              for stage,mode in (("configure","configure"),("runtime-build","runtime"))],
                  "coverage":{"required_units":[{"id":"runtime-floor","kind":"clang","source":"runtime.c","role":"runtime"}],
                              "required_outputs":["app"],"require_full_unit_inventory":True}}
        manifest = cls.directory/"recipe.json"
        manifest.write_text(json.dumps(recipe))
        run([sys.executable,ROOT/"scripts/ocore_runtime_capture.py","capture",manifest,
             "--source",cls.source,"--build",cls.build,"--output",cls.capture,
             "--unit-inventory",cls.build/"inventory.json","--cc",cls.sdk/"clang",
             "--cxx",cls.sdk/"clang++","--llvm-nm",cls.sdk/"llvm-nm"])
        cls.original = json.loads((cls.capture/"report.json").read_text())
        if not cls.original["capture_complete"] or len(cls.original["units"]) != 2:
            raise RuntimeError("complete two-unit real capture required")
        if len(cls.original["lowering_unit_ids"]) != 1 or len(cls.original["non_lowering_units"]) != 1:
            raise RuntimeError("actual source/runtime vs configure partition required")

    def setUp(self):
        self.report = copy.deepcopy(self.original)
        self.case = Path(tempfile.mkdtemp(prefix="case-",dir=self.directory))
        if not self.retain_artifacts:
            self.addCleanup(shutil.rmtree,self.case)

    def lower(self,kind="ir",expect_success=False):
        path = self.case/"capture.json"
        path.write_text(json.dumps(self.report))
        # Capture admission reconstructs the report from its independent
        # adjacent journal. Keep that original evidence unchanged when only
        # the caller-supplied report is tampered with.
        shutil.copyfile(self.capture/"session.json",self.case/"session.json")
        shutil.copytree(self.capture/"events",self.case/"events")
        output = self.case/"lowered"
        result = subprocess.run([str(self.olangc),str(path),"--native-runtime",
                                 "--native-isa",self.native_target,"--native-runtime-output",kind,*self.import_options,
                                 "-o",str(output)],capture_output=True,text=True,timeout=120)
        receipt_path = output/"coverage.json"
        self.assertTrue(receipt_path.is_file(),result.stdout+result.stderr)
        receipt = json.loads(receipt_path.read_text())
        self.assertEqual(result.returncode == 0,expect_success,result.stdout+result.stderr+json.dumps(receipt,indent=2))
        for field in ("runtime_complete","native_execution_qualified","dependency_closure_complete","artifact_complete","link_performed"):
            self.assertFalse(receipt[field],field)
        return receipt,output

    def rejected_preflight(self):
        receipt,_ = self.lower()
        self.assertFalse(receipt["capture_complete"])
        self.assertFalse(receipt["module_set_complete"])
        self.assertEqual(receipt["lowered_unit_count"],0)
        self.assertTrue(receipt["issues"])

    def test_actual_capture_to_verified_ir_retains_unused_runtime_and_excluded_probe(self):
        receipt,output = self.lower(expect_success=True)
        self.assertTrue(receipt["module_set_complete"])
        self.assertTrue(receipt["symbol_closure_complete"])
        self.assertEqual(receipt["captured_unit_count"],2)
        self.assertEqual(receipt["required_lowering_unit_count"],1)
        self.assertEqual(receipt["lowered_unit_count"],1)
        self.assertEqual(len(receipt["units"]),2)
        self.assertEqual(len(receipt["non_lowering_units"]),1)
        modules = list(output.glob("unit-*/module.native-ir.json"))
        self.assertEqual(len(modules),1)
        module = json.loads(modules[0].read_text())
        self.assertEqual({function["name"] for function in module["functions"]},
                         {"main","engine_add","cold_path"})
        self.assertTrue(receipt["native_module_dependency_closure_complete"])
        artifact_path = Path(receipt["module_set_artifact"]["path"])
        artifact = json.loads(artifact_path.read_text())
        self.assertEqual(artifact["format"],"ocore-native-module-set-v1")
        self.assertEqual(len(artifact["modules"]),1)
        self.assertEqual(json.loads(artifact["modules"][0]["native_ir"]),module)
        self.assertTrue(artifact["symbol_inventory"]["closed"])

    def test_module_set_survives_removal_of_imported_and_original_llvm_inputs(self):
        receipt,output = self.lower(expect_success=True)
        artifact = json.loads(Path(receipt["module_set_artifact"]["path"]).read_text())
        shutil.rmtree(output)
        hidden = []
        try:
            for unit in self.report["units"]:
                original = Path(unit["ir"]["path"])
                moved = original.with_name(original.name+".package-test-hidden")
                original.rename(moved)
                hidden.append((original,moved))
            for index,embedded in enumerate(artifact["modules"]):
                path = self.case/f"moved-{index}.native-ir.json"
                path.write_text(embedded["native_ir"])
                verification = self.case/f"moved-{index}.verification.json"
                run([self.ocorec,path,"--input-kind","native-ir","--verify-native","--receipt",verification])
                self.assertTrue(json.loads(verification.read_text())["verified"])
                obj = self.case/f"moved-{index}.o"
                run([self.ocorec,path,"--input-kind","native-ir","--emit","obj",
                     "--target",self.native_target,"-o",obj])
                self.assertTrue(obj.is_file())
        finally:
            for original,moved in hidden:
                moved.rename(original)

    def test_actual_module_set_recompiles_after_removing_capture_source_and_imported_modules(self):
        receipt,output = self.lower(expect_success=True)
        detached = self.case/"detached.native-ir.json"
        shutil.copyfile(receipt["module_set_artifact"]["path"],detached)
        shutil.rmtree(output)
        hidden = []
        try:
            for original in (self.source,self.build,self.capture):
                moved = original.with_name(original.name+".package-test-hidden")
                original.rename(moved)
                hidden.append((original,moved))
            reused = self.case/"reused"
            # Package lowering consumes its verified embedded modules; it needs
            # no foreign frontend, parser option, capture journal, or source.
            run([self.olangc,detached,"--native-runtime","--native-isa",self.native_target,
                 "--native-runtime-output","obj","-o",reused])
            record = json.loads((reused/"coverage.json").read_text())
            self.assertEqual(record["input_kind"],"native_module_set")
            self.assertFalse(record["source_capture_reverification_performed"])
            self.assertTrue(record["unit_lowering_complete"])
            self.assertTrue(record["native_module_dependency_closure_complete"])
            objects = list(reused.glob("unit-*/module.o"))
            self.assertEqual(len(objects),1)
            self.assertEqual(objects[0].read_bytes()[:4],b"\x7fELF")
            executable = self.case/"detached-host-carrier"
            run([self.sdk/"clang",objects[0],"-no-pie","-o",executable])
            self.assertEqual(run([executable]).returncode,0)
        finally:
            for original,moved in reversed(hidden):
                moved.rename(original)

    def test_actual_own_object_has_complete_definitions_and_executes_imported_main(self):
        receipt,output = self.lower(kind="obj",expect_success=True)
        self.assertTrue(receipt["module_set_complete"])
        objects = list(output.glob("unit-*/module.o"))
        self.assertEqual(len(objects),1)
        names = {line.split()[-1] for line in run([self.sdk/"llvm-nm","--defined-only",objects[0]]).stdout.splitlines()}
        self.assertTrue({"main","engine_add","cold_path"} <= names)
        self.assertNotIn("configure_probe",names)
        exe = self.case/"own-object-host-carrier"
        run([self.sdk/"clang",objects[0],"-no-pie","-o",exe])
        self.assertEqual(run([exe]).returncode,0)

    def test_inventory_definition_cannot_differ_from_actual_hashed_build_inventory(self):
        self.report["unit_inventory"]["definition"]["units"][0]["source"] = "another-source.c"
        self.rejected_preflight()

    def test_changed_inventory_file_is_not_accepted_by_stale_capture_flags(self):
        path = Path(self.report["unit_inventory"]["file"]["path"])
        original = path.read_bytes()
        try:
            path.write_bytes(original+b"\n ")
            self.rejected_preflight()
        finally:
            path.write_bytes(original)

    def test_lowering_unit_cannot_also_be_excluded_as_a_probe(self):
        runtime_id = self.report["lowering_unit_ids"][0]
        self.report["non_lowering_units"][0]["unit_id"] = runtime_id
        self.rejected_preflight()

    def test_duplicate_lowering_ids_cannot_count_as_complete_inventory(self):
        self.report["lowering_unit_ids"].append(self.report["lowering_unit_ids"][0])
        self.rejected_preflight()

    def test_missing_role_or_silently_dropped_invocation_unit_fails(self):
        probe_id = self.report["non_lowering_units"][0]["unit_id"]
        self.report["units"] = [unit for unit in self.report["units"] if unit["id"] != probe_id]
        self.rejected_preflight()

    def test_wrong_exclusion_reason_fails_against_inventory(self):
        self.report["non_lowering_units"][0]["evidence"]["reason"] = "forged role justification"
        self.rejected_preflight()

    def test_wrong_exclusion_build_step_fails_against_recorded_execution(self):
        self.report["non_lowering_units"][0]["evidence"]["build_step"]["index"] = 1
        self.rejected_preflight()

    def test_exclusion_requires_the_final_output_membership_graph(self):
        del self.report["runtime_output_membership"]
        self.rejected_preflight()

    def test_incomplete_final_output_membership_graph_cannot_admit_exclusions(self):
        self.report["runtime_output_membership"]["complete"] = False
        self.report["runtime_output_membership"]["issues"] = ["final link inputs could not be enumerated"]
        self.rejected_preflight()

    def test_runtime_contributing_invocation_cannot_be_excluded_as_a_probe(self):
        probe_id = self.report["non_lowering_units"][0]["unit_id"]
        owner = next(invocation["id"] for invocation in self.report["invocations"]
                     if any(unit["id"] == probe_id for unit in invocation["units"]))
        self.report["runtime_output_membership"]["contributing_invocation_ids"].append(owner)
        self.rejected_preflight()

    def test_selected_source_must_match_the_bound_complete_inventory_selector(self):
        runtime_id = self.report["lowering_unit_ids"][0]
        replacement = str(self.source/"not-in-the-inventory.c")
        # Keep the journal and global unit record identical, and the original
        # LLVM bytes/hash intact. Completeness must still recheck the source
        # selector in the independently hash-bound build inventory.
        for unit in self.report["units"]:
            if unit["id"] == runtime_id:
                unit["source"]["path"] = replacement
        for invocation in self.report["invocations"]:
            for unit in invocation["units"]:
                if unit["id"] == runtime_id:
                    unit["source"]["path"] = replacement
        self.rejected_preflight()

    def test_changed_exclusion_artifact_is_rejected_before_any_lowering(self):
        path = Path(self.report["non_lowering_units"][0]["evidence"]["artifacts"][0]["path"])
        original = path.read_bytes()
        try:
            path.write_bytes(original+b"changed")
            self.rejected_preflight()
        finally:
            path.write_bytes(original)

    def test_original_captured_llvm_bytes_cannot_change_after_capture(self):
        selected = self.report["lowering_unit_ids"][0]
        unit = next(unit for unit in self.report["units"] if unit["id"] == selected)
        path = Path(unit["ir"]["path"])
        original = path.read_bytes()
        try:
            path.write_bytes(original+b"\n; post-capture byte mutation\n")
            self.rejected_preflight()
        finally:
            path.write_bytes(original)


